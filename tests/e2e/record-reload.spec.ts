import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function createStory(page: Page, title: string) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Новая история', exact: true }).click()
  await page.getByRole('textbox', { name: 'Название истории', exact: true }).fill(title)
  await page.getByRole('button', { name: 'Создать историю', exact: true }).click()
  await expect(page.getByLabel('Доска', { exact: true })).toBeVisible()
}

test('records real edits and restores the story after reload', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name === 'mobile', 'Full authoring is verified on desktop')
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => {
    navigator.mediaDevices.getUserMedia = () => { throw new Error('Microphone must stay off') }
  })
  await createStory(page, 'Тест: архитектура')
  await page.getByRole('button', { name: 'Блок', exact: true }).click()
  await page.getByRole('textbox', { name: 'Текст объекта', exact: true }).fill('Клиент')
  await page.getByRole('button', { name: 'Блок', exact: true }).click()
  await page.getByRole('textbox', { name: 'Текст объекта', exact: true }).fill('Сервер')
  await page.getByRole('button', { name: 'Связь', exact: true }).click()
  await page.getByRole('button', { name: 'Блок: Клиент', exact: true }).click()
  await page.getByRole('button', { name: 'Блок: Сервер', exact: true }).click()
  await expect(page.locator('[data-connection-id]')).toHaveCount(1)
  await page.getByRole('button', { name: 'Выбрать', exact: true }).click()
  await page.getByRole('button', { name: 'Записать', exact: true }).click()
  const node = page.getByRole('button', { name: 'Блок: Клиент', exact: true })
  await node.click()
  const startingX = Number(await page.getByLabel('Позиция X', { exact: true }).inputValue())
  const box = await node.boundingBox()
  if (!box) throw new Error('Node was not rendered')
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 120, box.y + box.height / 2 + 60, { steps: 8 })
  await page.mouse.up()
  await expect.poll(async () => Number(await page.getByLabel('Позиция X', { exact: true }).inputValue())).toBeGreaterThan(startingX + 80)
  await page.getByRole('button', { name: 'Текст', exact: true }).click()
  await page.getByRole('textbox', { name: 'Текст объекта', exact: true }).fill('Повторный запрос')
  await expect(page.locator('.time-value')).toHaveText(/00:0[1-9]/)
  await page.getByRole('button', { name: 'Остановить запись', exact: true }).click()
  await expect(page.getByLabel('Состояние сохранения', { exact: true })).toHaveText(/Сохранено/)
  await page.screenshot({ path: 'artifacts/visual/p1/editor-desktop.png', fullPage: true, animations: 'disabled' })
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Название истории', exact: true })).toHaveValue('Тест: архитектура')
  await expect(page.getByRole('button', { name: 'Текст: Повторный запрос', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Просмотр', exact: true }).click()
  const position = page.getByRole('slider', { name: 'Позиция воспроизведения', exact: true })
  await position.focus()
  await position.press('End')
  await expect(page.getByText('Повторный запрос', { exact: true })).toBeVisible()
  await position.press('Home')
  await expect(page.getByText('Повторный запрос', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Воспроизвести', exact: true }).click()
  await expect.poll(async () => Number(await position.inputValue())).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Пауза', exact: true }).click()
  await page.getByLabel('Доска', { exact: true }).focus()
  await page.keyboard.press('b')
  await page.getByRole('button', { name: 'Вернуться в редактор', exact: true }).click()
  await expect(page.locator('[data-object-id]')).toHaveCount(3)
  await page.getByRole('button', { name: 'Мои истории', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Тест: архитектура', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

test('recovers a recording interrupted by reload', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name === 'mobile', 'Recovery of authoring is verified on desktop')
  await createStory(page, 'Прерванная запись')
  await page.getByRole('button', { name: 'Блок', exact: true }).click()
  await page.getByRole('button', { name: 'Записать', exact: true }).click()
  await page.getByRole('textbox', { name: 'Текст объекта', exact: true }).fill('Сохранённый фрагмент')
  await expect(page.getByLabel('Состояние сохранения', { exact: true })).toHaveText(/Сохранено/)
  await page.reload()
  await expect(page.getByText('Запись была прервана', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Блок: Сохранённый фрагмент', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Просмотр', exact: true })).toBeEnabled()
})

test('shows an empty studio and plays a sample on the current device', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Место для вашей первой истории', exact: true })).toBeVisible()
  await page.screenshot({ path: 'artifacts/visual/p1/home-' + testInfo.project.name + '.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Смотреть «Почему заказ создался дважды?»', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Почему заказ создался дважды?', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Воспроизвести', exact: true }).click()
  const position = page.getByRole('slider', { name: 'Позиция воспроизведения', exact: true })
  await expect.poll(async () => Number(await position.inputValue())).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Пауза', exact: true }).click()
  await position.focus()
  await position.press('End')
  await expect(page.getByText('Ключ идемпотентности', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'artifacts/visual/p1/player-' + testInfo.project.name + '.png', fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

test('protects a saved recording from an older tab with more local edits', async ({ page, context }, testInfo) => {
  test.skip(testInfo.project.name === 'mobile', 'Concurrent authoring is verified on desktop')
  await createStory(page, 'Две вкладки')
  const other = await context.newPage()
  await other.goto(page.url())
  await expect(other.getByLabel('Доска', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Блок', exact: true }).click()
  await page.getByRole('button', { name: 'Записать', exact: true }).click()
  await page.getByRole('textbox', { name: 'Текст объекта', exact: true }).fill('Запись вкладки A')
  await page.getByRole('button', { name: 'Остановить запись', exact: true }).click()
  await expect(page.getByLabel('Состояние сохранения', { exact: true })).toHaveText(/Сохранено/)
  for (let index = 0; index < 8; index++) {
    await other.getByRole('button', { name: 'Блок', exact: true }).click()
  }
  await expect(other.getByLabel('Состояние сохранения', { exact: true })).toHaveText(/Не сохранено/)
  await other.getByRole('alert').getByRole('button', { name: 'Повторить', exact: true }).click()
  await expect(other.getByLabel('Состояние сохранения', { exact: true })).toHaveText(/Не сохранено/)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Блок: Запись вкладки A', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Просмотр', exact: true })).toBeEnabled()
  await other.close()
})
